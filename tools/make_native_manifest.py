"""Regenerate native_manifest.py and the embedded pristine copies.

Run after rebuilding the native module:

    native/build_macos.sh && native/build_windows.sh
    python tools/make_native_manifest.py

It writes:
    namepicker/native_manifest.py        pinned SHA-256 per platform
    namepicker/native_backup/<name>.gz   pristine copies used for one-click restore
"""

import base64
import gzip
import hashlib
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
sys.path.insert(0, _HERE)

from _encoding import utf8_output

utf8_output()

TARGETS = {
    ("darwin", "sign"): os.path.join(_ROOT, "native", "cmd_sign"),
    ("darwin", "verify"): os.path.join(_ROOT, "native", "cmd_verify"),
    ("win32", "sign"): os.path.join(_ROOT, "native", "cmd_sign.exe"),
    ("win32", "verify"): os.path.join(_ROOT, "native", "cmd_verify.exe"),
}
BACKUP_DIR = os.path.join(_ROOT, "namepicker", "native_backup")
MANIFEST = os.path.join(_ROOT, "namepicker", "native_manifest.py")


def main() -> int:
    os.makedirs(BACKUP_DIR, exist_ok=True)
    entries = []
    for (platform, role), path in TARGETS.items():
        if not os.path.isfile(path):
            print(f"[SKIP] {platform}/{role}: {path} not found")
            continue
        raw = open(path, "rb").read()
        digest = hashlib.sha256(raw).hexdigest()
        name = os.path.basename(path) + ".gz"
        with gzip.open(os.path.join(BACKUP_DIR, name), "wb", compresslevel=9) as fh:
            fh.write(raw)
        entries.append((platform, role, os.path.basename(path), digest, len(raw), name))
        print(f"[OK] {platform}/{role}: {os.path.basename(path)} {len(raw)} bytes sha256={digest[:16]}…")

    lines = [
        '"""Pinned hashes of the native modules (generated by tools/make_native_manifest.py).',
        "",
        "Two binaries per platform: sign (has the key) and verify (public key only).",
        "Do not edit by hand: rebuild, then re-run the tool.",
        '"""',
        "",
        "# platform -> role -> (binary name, sha256 hex, size in bytes, backup file name)",
        "NATIVE = {",
    ]
    by_platform: dict[str, list] = {}
    for platform, role, name, digest, size, backup in entries:
        by_platform.setdefault(platform, []).append((role, name, digest, size, backup))
    for platform, items in by_platform.items():
        lines.append(f'    "{platform}": {{')
        for role, name, digest, size, backup in items:
            lines.append(f'        "{role}": ("{name}", "{digest}", {size}, "{backup}"),')
        lines.append("    },")
    lines += ["}", ""]
    with open(MANIFEST, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"[i] wrote {MANIFEST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
